import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import sharp from 'sharp';
import subsetFont from 'subset-font';

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const scanPaths = ['index.html', 'src/js/main.js'];
const extraIcons = ['moon-stars'];

const baseRules = `.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
    display: inline-block;
    font-family: bootstrap-icons !important;
    font-style: normal;
    font-weight: normal !important;
    font-variant: normal;
    text-transform: none;
    line-height: 1;
    vertical-align: -.125em;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}
`;

async function usedIconNames(root) {
    const names = new Set(extraIcons);

    for (const relativePath of scanPaths) {
        const text = await readFile(resolve(root, relativePath), 'utf8');

        for (const [, name] of text.matchAll(/\bbi-([a-z0-9-]+)\b/g)) {
            if (name !== 'icons') {
                names.add(name);
            }
        }
    }

    return [...names].sort();
}

async function iconCodepoints(root) {
    const css = await readFile(
        resolve(root, 'node_modules/bootstrap-icons/font/bootstrap-icons.css'),
        'utf8',
    );
    const entries = css.matchAll(/\.bi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)";/g);

    return new Map([...entries].map(([, name, code]) => [name, code]));
}

async function buildIcons(root) {
    const names = await usedIconNames(root);
    const codepoints = await iconCodepoints(root);
    const missing = names.filter((name) => !codepoints.has(name));

    if (missing.length) {
        throw new Error(`Unknown icons: ${missing.join(', ')}`);
    }

    const characters = names.map((name) => String.fromCodePoint(parseInt(codepoints.get(name), 16)));
    const source = await readFile(
        resolve(root, 'node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2'),
    );
    const subset = await subsetFont(source, characters.join(''), { targetFormat: 'woff2' });
    const fontPath = resolve(root, 'src/assets/fonts/bootstrap-icons-subset.woff2');

    await mkdir(dirname(fontPath), { recursive: true });
    await writeFile(fontPath, subset);

    const rules = names
        .map((name) => `.bi-${name}::before { content: "\\${codepoints.get(name)}"; }`)
        .join('\n');

    await writeFile(
        resolve(root, 'src/scss/_icons.scss'),
        '// Generated by scripts/generate-assets.mjs - do not edit by hand.\n' +
            '@font-face {\n' +
            '    font-family: "bootstrap-icons";\n' +
            '    src: url("../assets/fonts/bootstrap-icons-subset.woff2") format("woff2");\n' +
            '    font-display: swap;\n' +
            '}\n\n' +
            `${baseRules}\n${rules}\n`,
        'utf8',
    );

    console.log(`[generated-assets] icon subset: ${names.length} glyphs (${subset.length} bytes)`);
}

async function buildImage(root) {
    await sharp(resolve(root, 'public/images/profile.png'))
        .webp({ quality: 82, effort: 6 })
        .toFile(resolve(root, 'public/images/profile.webp'));

    console.log('[generated-assets] portrait written to public/images/profile.webp');
}

export async function generateAssets({ root = defaultRoot } = {}) {
    await buildIcons(root);
    await buildImage(root);
}

const entry = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';

if (entry === import.meta.url) {
    await generateAssets();
}
